"""V10 S3 Writer — Uploads V10 research data to dedicated bucket.

Bucket: v10-engine (eu-west-2)
Structure: v10/{dataset}/symbol={PAIR}/date={YYYY-MM-DD}/{dataset}.jsonl

Only real trading symbols. No test/mock data.
Schema validated before upload. Never raises.
"""

from __future__ import annotations

import json
import logging
from datetime import datetime, timezone
from typing import Any

from core.v10.schema_contract import SCHEMA_VERSION, validate_decision_record

logger = logging.getLogger(__name__)

# ═══════════════════════════════════════════════════════════════
# CONFIGURATION
# ═══════════════════════════════════════════════════════════════

BUCKET_NAME = "v10-engine"
BUCKET_REGION = "eu-west-2"

# Only real trading symbols may be written
ALLOWED_SYMBOLS = frozenset({
    "EURUSD", "GBPUSD", "USDJPY", "USDCHF", "USDCAD", "AUDUSD", "NZDUSD",
    "NAS100", "US500", "XAUUSD",
    # Broker-suffixed variants
    "EURUSD_SB", "GBPUSD_SB", "USDJPY_SB", "USDCHF_SB", "USDCAD_SB",
    "AUDUSD_SB", "NZDUSD_SB", "NAS100_SB", "US500_SB", "XAUUSD_SB",
})

# Forbidden prefixes (test/mock/debug)
FORBIDDEN_PREFIXES = ("TEST", "MOCK", "FAKE", "DUMMY", "FIXTURE", "DEBUG")

# Minimum observation_id length (production IDs are 16-char hex from sha256)
_MIN_OBSERVATION_ID_LENGTH = 12


def validate_observation_id(obs_id: str) -> tuple[bool, str]:
    """
    Validate an observation_id is production-quality.

    Production IDs are 16-char lowercase hex strings generated by
    sha256(symbol_timestamp)[:16]. This validator rejects:
      - Empty/missing IDs
      - IDs shorter than 12 characters (test artifacts like "no_boto", "abc")
      - IDs starting with forbidden prefixes (test_, mock_, fake_, etc.)
      - IDs containing only digits (likely raw timestamps)

    Returns (valid, reason).
    """
    if not obs_id:
        return False, "observation_id is empty"
    if len(obs_id) < _MIN_OBSERVATION_ID_LENGTH:
        return False, f"observation_id '{obs_id}' too short ({len(obs_id)} < {_MIN_OBSERVATION_ID_LENGTH})"
    obs_upper = obs_id.upper()
    for prefix in FORBIDDEN_PREFIXES:
        if obs_upper.startswith(prefix):
            return False, f"observation_id '{obs_id}' has forbidden prefix '{prefix}'"
    if obs_id.isdigit():
        return False, f"observation_id '{obs_id}' is purely numeric (likely raw timestamp)"
    return True, "valid"


# ═══════════════════════════════════════════════════════════════
# PRODUCTION WRITE GUARD
# ═══════════════════════════════════════════════════════════════


def _is_test_environment() -> bool:
    """
    Detect if running under a test/dev environment.

    Returns True if ANY of these are true:
      - PYTEST_CURRENT_TEST env var exists (set by pytest automatically)
      - 'pytest' or '_pytest' is in sys.modules (pytest is imported)
      - TEST_MODE config flag is True
      - ENVIRONMENT config is "TEST" or "DEV"
    """
    import os
    import sys

    # Env var set by pytest for every test
    if os.environ.get("PYTEST_CURRENT_TEST"):
        return True

    # pytest loaded in process
    if "pytest" in sys.modules or "_pytest" in sys.modules:
        return True

    # Explicit config flags
    try:
        from core import config
        if getattr(config, "TEST_MODE", False):
            return True
        env = getattr(config, "ENVIRONMENT", "PRODUCTION").upper()
        if env in ("TEST", "DEV", "DEVELOPMENT", "STAGING"):
            return True
    except ImportError:
        pass

    return False


def _production_write_guard() -> tuple[bool, str]:
    """
    Runtime gate: blocks ALL S3 writes unless production conditions are met.

    Requires ALL of:
      1. NOT running under test environment
      2. ENGINE_MODE == "V10"
      3. LIVE_MODE == True
      4. ALLOW_PRODUCTION_S3_WRITE == True

    This guard lives inside s3_writer.py so that even direct callers
    (scripts, notebooks, smoke tests) are blocked.

    Returns (allowed, reason).
    """
    # Hard stop: test environment can NEVER write to production bucket
    if _is_test_environment():
        return False, "test_environment_detected"

    try:
        from core import config
    except ImportError:
        return False, "config module unavailable"

    engine_mode = getattr(config, "ENGINE_MODE", "LEGACY")
    live_mode = getattr(config, "LIVE_MODE", False)
    allow_write = getattr(config, "ALLOW_PRODUCTION_S3_WRITE", False)

    if engine_mode != "V10":
        return False, f"ENGINE_MODE={engine_mode} (requires V10)"
    if not live_mode:
        return False, "LIVE_MODE=False (not live trading runtime)"
    if not allow_write:
        return False, "ALLOW_PRODUCTION_S3_WRITE=False (production writes disabled)"

    return True, "V10_LIVE"


