def upload_events(events: list[dict[str, Any]], observation_id: str = "") -> bool:
    """
    Upload V10 pipeline events (full reasoning timeline) to S3.

    All events for one pipeline evaluation are written as one JSONL batch.
    Schema: v10_event_v1
    """
    if not events:
        return False

    # Production write guard
    allowed, reason = _production_write_guard()
    if not allowed:
        logger.debug("[S3 GUARD] bucket=%s action=BLOCKED dataset=events reason=%s", BUCKET_NAME, reason)
        return False

    # Validate first event for symbol/timestamp
    first = events[0]
    symbol = first.get("symbol", "")
    if not _is_valid_symbol(symbol):
        logger.debug("[V10_S3] events rejected: invalid symbol '%s'", symbol)
        return False

    # Validate all events
    for event in events:
        if not _validate_event(event):
            return False

    symbol = _normalize_symbol(symbol)
    date_str = _extract_date(first.get("timestamp_utc", 0))
    obs_id = observation_id or first.get("observation_id", "unknown")
    key = f"v10/events/symbol={symbol}/date={date_str}/events_{obs_id}.jsonl"

    # Write all events as one JSONL batch
    try:
        import boto3
        client = boto3.client("s3", region_name=BUCKET_REGION)
        lines = "".join(json.dumps(e, default=str) + "\n" for e in events)
        client.put_object(
            Bucket=BUCKET_NAME,
            Key=key,
            Body=lines.encode("utf-8"),
            ContentType="application/jsonl",
        )
        logger.info("[V10_S3] events uploaded: %s (%d events)", key, len(events))
        return True
    except ImportError:
        logger.debug("[V10_S3] boto3 not available — event upload skipped")
        return False
    except Exception as exc:
        logger.warning("[V10_S3] event upload failed: %s", exc)
        return False


# ═══════════════════════════════════════════════════════════════
# VALIDATION
# ═══════════════════════════════════════════════════════════════


def _validate_for_upload(record: dict, dataset: str) -> bool:
    """Validate record before S3 upload."""
    # Symbol check
    symbol = record.get("symbol", "")
    if not _is_valid_symbol(symbol):
        logger.debug("[V10_S3] rejected: invalid symbol '%s'", symbol)
        return False

    # Timestamp range check — reject stale/default/future timestamps
    from core.v10.pipeline_events import validate_timestamp
    ts = record.get("timestamp_utc", 0)
    ts_valid, ts_reason = validate_timestamp(ts)
    if not ts_valid:
        logger.debug("[V10_S3] rejected: %s", ts_reason)
        return False

    # Observation ID validation — central validator
    obs_id = record.get("observation_id", "")
    obs_valid, obs_reason = validate_observation_id(obs_id)
    if not obs_valid:
        logger.debug("[V10_S3] rejected: %s", obs_reason)
        return False

    # Schema validation (decisions only — executions/outcomes have lighter schemas)
    if dataset == "decision":
        valid, violations = validate_decision_record(record)
        if not valid:
            logger.debug("[V10_S3] schema violation: %s", violations[:3])
            return False

    return True


EVENT_SCHEMA_VERSION = "v10_event_v1"

_VALID_EVENT_TYPES = frozenset({
    "V10_MARKET_STATE_COMPLETE",
    "V10_OPPORTUNITY_COMPLETE",
    "V10_STRATEGY_COMPLETE",
    "V10_HORIZON_COMPLETE",
    "V10_ENTRY_COMPLETE",
    "V10_RISK_COMPLETE",
    "V10_EXECUTION_COMPLETE",
    "V10_DECISION_COMPLETE",
})


def _validate_event(event: dict) -> bool:
    """Validate a single V10 event before S3 upload."""
    from core.v10.pipeline_events import validate_timestamp

    # Required fields
    if not event.get("observation_id"):
        return False
    if not event.get("symbol"):
        return False
    if not event.get("event_type"):
        return False

    # Observation ID validation
    obs_valid, _ = validate_observation_id(event.get("observation_id", ""))
    if not obs_valid:
        return False

    # Timestamp validity
    ts = event.get("timestamp_utc", 0)
    valid, _ = validate_timestamp(ts)
    if not valid:
        return False

    # Engine version
    if event.get("engine_version") != "V10":
        return False

    # Event type must be recognised
    if event.get("event_type") not in _VALID_EVENT_TYPES:
        return False

    return True


def _is_valid_symbol(symbol: str) -> bool:
    """Check if symbol is a real trading instrument (not test/mock)."""
    if not symbol:
        return False
    s = symbol.upper()
    # Forbidden prefixes
    for prefix in FORBIDDEN_PREFIXES:
        if s.startswith(prefix):
            return False
    # Must be in allowed set (or canonical form of allowed)
    canonical = s.rstrip("_SB").rstrip(".C").rstrip("_CFD")
    return s in ALLOWED_SYMBOLS or canonical in ALLOWED_SYMBOLS


def _normalize_symbol(symbol: str) -> str:
    """Normalize to canonical form for S3 key."""
    s = symbol.upper()
    for suffix in ("_SB", ".C", "_CFD"):
        if s.endswith(suffix):
            s = s[:-len(suffix)]
    return s


def _extract_date(timestamp: float) -> str:
    """Extract YYYY-MM-DD from unix timestamp."""
    if timestamp > 0:
        dt = datetime.fromtimestamp(timestamp, tz=timezone.utc)
    else:
        dt = datetime.now(timezone.utc)
    return dt.strftime("%Y-%m-%d")


# ═══════════════════════════════════════════════════════════════
# S3 TRANSPORT
# ═══════════════════════════════════════════════════════════════


def _append_to_s3(key: str, record: dict) -> bool:
    """Append a JSONL record to S3. Never raises."""
    obs_id = record.get("observation_id", record.get("decision_id", "unknown"))
    try:
        import boto3
        client = boto3.client("s3", region_name=BUCKET_REGION)
        line = json.dumps(record, default=str) + "\n"

        # S3 doesn't support append — use a unique key per record
        unique_key = key.replace(".jsonl", f"_{obs_id}.jsonl")

        logger.info("[V10_S3] step=put_object obs_id=%s key=%s", obs_id, unique_key)
        client.put_object(
            Bucket=BUCKET_NAME,
            Key=unique_key,
            Body=line.encode("utf-8"),
            ContentType="application/jsonl",
        )
        logger.info("[V10_S3] step=uploaded obs_id=%s key=%s", obs_id, unique_key)
        return True

    except ImportError:
        logger.info("[V10_S3] step=skipped obs_id=%s reason=boto3_unavailable", obs_id)
        return False
    except Exception as exc:
        logger.warning("[V10_S3] step=failed obs_id=%s error=%s", obs_id, exc)
        return False
